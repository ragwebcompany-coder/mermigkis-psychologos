export function bandForEl(score: number): AisBand {
  if (score <= 3) {
    return {
      label: "Χωρίς ένδειξη αϋπνίας",
      range: "0–3",
      tone: "calm",
      headline: "Ο ύπνος σας φαίνεται να λειτουργεί.",
      body: "Η βαθμολογία σας δεν υποδεικνύει κλινικά σημαντική αϋπνία. Αν παρόλα αυτά νιώθετε ότι κάτι δεν πάει καλά με τον ύπνο σας — έντονο ροχαλητό, αναπνευστικές παύσεις, κινήσεις των ποδιών, εφιάλτες — αξίζει να το συζητήσετε, γιατί αυτά είναι άλλες διαταραχές του ύπνου, όχι αϋπνία.",
    };
  }
  if (score <= 5) {
    return {
      label: "Οριακή βαθμολογία",
      range: "4–5",
      tone: "watch",
      headline: "Βρίσκεστε ακριβώς κάτω από το όριο.",
      body: "Η βαθμολογία σας είναι οριακή: υπάρχει δυσκολία, αλλά δεν φτάνει το κλινικό όριο της κλίμακας. Συχνά αυτό είναι το στάδιο όπου μια σύντομη παρέμβαση αποδίδει τα περισσότερα — πριν εγκατασταθούν οι συνήθειες και οι σκέψεις που κάνουν την αϋπνία χρόνια.",
    };
  }
  if (score <= 11) {
    return {
      label: "Πιθανή αϋπνία",
      range: "6–11",
      tone: "alert",
      headline: "Η βαθμολογία σας υπερβαίνει το όριο της κλίμακας.",
      body: "Βαθμολογία 6 και άνω θεωρείται ένδειξη αϋπνίας και χρήζει αξιολόγησης. Η CBT-I είναι η θεραπεία πρώτης γραμμής για ακριβώς αυτή την εικόνα, με αποτελέσματα που διατηρούνται και μετά το τέλος των συνεδριών.",
    };
  }
  return {
    label: "Έντονη συμπτωματολογία",
    range: "12–24",
    tone: "alert",
    headline: "Η εικόνα που περιγράφετε είναι βαριά.",
    body: "Η βαθμολογία σας δείχνει σοβαρή επιβάρυνση τόσο του νυχτερινού ύπνου όσο και της ημέρας σας. Είναι σημαντικό να γίνει κλινική αξιολόγηση — τόσο για την ίδια την αϋπνία όσο και για να αποκλειστούν άλλες διαταραχές ύπνου που μπορεί να συνυπάρχουν.",
  };
}
